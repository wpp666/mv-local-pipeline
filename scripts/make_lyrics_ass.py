# -*- coding: utf-8 -*-
"""阶段 5：由歌词配置生成 ASS 字幕（片头标题 + 中英双行歌词 + 片尾落款）。

歌词配置是唯一数据源，脚本只负责版式。数据与逻辑分开，换歌只改 JSON。

用法（在 <project>/production 下）：
    python make_lyrics_ass.py                       # 读 lyrics/lyrics.json -> lyrics/master.ass
    python make_lyrics_ass.py --lyrics lyrics/other.json --out lyrics/other.ass
    python make_master.py --ass lyrics/master.ass   # 再烧进成片

配置字段（见 assets/lyrics.template.json）：
    title / title_en / credit / director / year     任一为空则不出那一行
    timing.title_in / title_en_in / sub_in / title_out
    timing.credit_in / credit_out                   缺省则由末句位置推导
    lines[]: {start, end, cn, en}                   en 可空
"""
import argparse
import json
from pathlib import Path

import mvconfig

CFG = mvconfig.CFG
PROD = CFG.project_root / "production"
DEFAULT_LYRICS = PROD / "lyrics" / "lyrics.json"

# 版式标准：暖象牙白 + 深棕描边；中文楷体，西文衬线；歌词在下三分之一
HEADER = """[Script Info]
; MV lyrics layer generated by mv-local-pipeline / make_lyrics_ass.py
ScriptType: v4.00+
PlayResX: 1024
PlayResY: 576
WrapStyle: 2
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Lyric,KaiTi,40,&H00D8EAF0,&H00D8EAF0,&H64201A16,&H96000000,0,0,0,0,100,100,2.5,0,1,1.6,0.6,2,56,56,74,1
Style: Eng,Georgia,22,&H00DAE4E8,&H00DAE4E8,&H64201A16,&H96000000,0,0,0,0,100,100,1.5,0,1,1.3,0.4,2,56,56,38,1
Style: Title,KaiTi,58,&H00D8EAF0,&H00D8EAF0,&H64201A16,&H96000000,0,0,0,0,100,100,8,0,1,1.8,0.6,8,80,80,106,1
Style: TitleEn,Georgia,26,&H00DAE4E8,&H00DAE4E8,&H64201A16,&H96000000,0,0,0,0,100,100,2,0,1,1.4,0.4,8,80,80,186,1
Style: Sub,Georgia,20,&H00C8D0D4,&H00C8D0D4,&H64201A16,&H96000000,0,0,0,0,100,100,2,0,1,1.2,0.4,8,80,80,236,1
Style: Credit,Georgia,26,&H00D8EAF0,&H00D8EAF0,&H64201A16,&H96000000,0,0,0,0,100,100,2,0,1,1.5,0.5,2,80,80,96,1
Style: Credit2,Georgia,22,&H00DAE4E8,&H00DAE4E8,&H64201A16,&H96000000,0,0,0,0,100,100,2,0,1,1.4,0.4,2,80,80,52,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""

T_FADE = r"{\fad(280,340)}"       # 歌词
H_FADE = r"{\fad(650,750)}"       # 片头
C_FADE = r"{\fad(700,900)}"       # 片尾


def ts(sec):
    if sec < 0:
        sec = 0
    cs = int(round(sec * 100))
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, c = divmod(rem, 100)
    return f"{h}:{m:02d}:{s:02d}.{c:02d}"


def ev(style, start, end, text, fade):
    return f"Dialogue: 0,{ts(start)},{ts(end)},{style},,0,0,0,,{fade}{text}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lyrics", default=str(DEFAULT_LYRICS))
    ap.add_argument("--out", default=None, help="默认写到歌词配置同目录的 master.ass")
    args = ap.parse_args()

    src = Path(args.lyrics)
    if not src.is_absolute():
        src = PROD / src
    if not src.exists():
        raise SystemExit(f"找不到歌词配置：{src}")
    info = json.loads(src.read_text(encoding="utf-8"))

    lines = info["lines"]
    timing = info.get("timing", {})
    out_path = Path(args.out) if args.out else src.with_name("master.ass")
    if not out_path.is_absolute():
        out_path = PROD / out_path
    out_path.parent.mkdir(parents=True, exist_ok=True)

    title_in = timing.get("title_in", 2.5)
    title_en_in = timing.get("title_en_in", title_in + 0.7)
    sub_in = timing.get("sub_in", title_in + 1.5)
    title_out = timing.get("title_out", 12.5)

    last_end = max(l["end"] for l in lines) if lines else 0.0
    credit_in = timing.get("credit_in", last_end + 2.0)
    credit_out = timing.get("credit_out", credit_in + 6.8)

    out = [HEADER]
    if info.get("title"):
        out.append(ev("Title", title_in, title_out, info["title"], H_FADE))
    if info.get("title_en"):
        out.append(ev("TitleEn", title_en_in, title_out, info["title_en"], H_FADE))
    if info.get("credit"):
        out.append(ev("Sub", sub_in, title_out, info["credit"], H_FADE))

    for line in lines:
        out.append(ev("Lyric", line["start"], line["end"], line["cn"], T_FADE))
        if line.get("en"):
            out.append(ev("Eng", line["start"], line["end"], line["en"], T_FADE))

    if info.get("director") or info.get("year"):
        if info.get("director"):
            out.append(ev("Credit", credit_in, credit_out, info["director"], C_FADE))
        if info.get("year"):
            out.append(ev("Credit2", credit_in, credit_out, info["year"], C_FADE))

    out_path.write_text("".join(out), encoding="utf-8")

    print(f"已写入 {out_path}")
    print(f"  片头 {info.get('title','')} / {info.get('title_en','')} / {info.get('credit','')}"
          f"  [{title_in}-{title_out}s]")
    print(f"  歌词 {len(lines)} 句  [{lines[0]['start'] if lines else 0}-{last_end}s]，"
          f"{'中英双行' if all(l.get('en') for l in lines) and lines else '中英混排'}")
    print(f"  片尾 {info.get('director','')} / {info.get('year','')}  [{credit_in}-{credit_out}s]")
    for i, l in enumerate(lines, 1):
        print(f"  {i:>3}  {l['start']:>8.3f}  {l['end']:>8.3f}  {l['cn']}"
              + (f" / {l['en']}" if l.get("en") else ""))


if __name__ == "__main__":
    main()
